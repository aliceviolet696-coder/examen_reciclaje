-- Script completo para PostgreSQL
-- ============================================================
-- OPCIÓN 1 - psql (ejecuta todo el archivo):
--   psql -U postgres -f database/init.sql
--
-- OPCIÓN 2 - pgAdmin:
--   1. Ejecute SOLO la línea CREATE DATABASE.
--   2. Conéctese a la base reciclaje_db.
--   3. Ejecute desde CREATE TABLE hasta el final.
--
-- Nota: Spring Boot también crea la tabla automáticamente
-- (spring.jpa.hibernate.ddl-auto=update) al iniciar la API.
-- ============================================================

CREATE DATABASE reciclaje_db;

\connect reciclaje_db

CREATE TABLE IF NOT EXISTS puntos_reciclaje (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre varchar(100) NOT NULL,
    sector varchar(100) NOT NULL,
    material varchar(100) NOT NULL,
    capacidad integer NOT NULL,
    CONSTRAINT puntos_reciclaje_capacidad_check CHECK (capacidad >= 0)
);

-- Datos de ejemplo: se insertan solo si la tabla está vacía.
INSERT INTO puntos_reciclaje (nombre, sector, material, capacidad)
SELECT v.nombre, v.sector, v.material, v.capacidad
FROM (VALUES
    ('EcoPunto Central', 'Centro Histórico', 'Plástico', 250),
    ('Punto Verde Norte', 'La Carolina', 'Vidrio', 180)
) AS v(nombre, sector, material, capacidad)
WHERE NOT EXISTS (SELECT 1 FROM puntos_reciclaje);

-- Verificación
SELECT * FROM puntos_reciclaje ORDER BY id;

